ICST_CSV = "Data;ICST com ajuste;ICST sem ajuste\n01/2025;93,1;92,4\n02/2025;94,0;\n".encode(
    "latin1"
)
LOAD = "20261201T060000Z"


def values(serie) -> list:
    """Valores da coluna com nulo como None (o pandas mostra string nula como <NA>)."""
    return [None if pd.isna(v) else v for v in serie]


class FakeS3:
    """O que as tasks chamam do S3Hook, sobre um dict chave -> (bytes, metadado)."""

    def __init__(self):
        self.objects: dict[str, tuple[bytes, dict]] = {}

    def list_keys(self, bucket, prefix=""):
        return [k for k in self.objects if k.startswith(prefix)]

    def get_conn(self):
        objects = self.objects

        class Client:
            def upload_file(self, path, bucket, key, ExtraArgs=None):
                objects[key] = (Path(path).read_bytes(), (ExtraArgs or {}).get("Metadata", {}))

            def head_object(self, Bucket, Key):
                return {"Metadata": objects[Key][1]}

        return Client()

    def download_file(self, key, bucket, local_path, preserve_file_name, use_autogenerated_subdir):
        dst = Path(local_path) / Path(key).name
        dst.write_bytes(self.objects[key][0])
        return str(dst)

    def load_file(self, filename, key, bucket, replace=False):
        self.objects[key] = (Path(filename).read_bytes(), {})


class FakePg:
    def __init__(self):
        self.rows = []

    def get_records(self, sql):
        return []

    def insert_rows(self, table, rows, fields, **kw):
        self.rows += rows


@pytest.fixture
def icst(monkeypatch, tmp_path):
    """O módulo da DAG com lake, banco e contexto falsos; `run(task_id, *args)` chama a task."""
    mod = importlib.import_module("dags.snh.data_ingest.fgv.icst_ingest_dag")
